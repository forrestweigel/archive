import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { archiveFormat } from "../lib/format.mjs";

export function renderShareCard(template, format = archiveFormat) {
  const values = { ...format, releaseUpper: format.release.toUpperCase() };
  const html = template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!Object.hasOwn(values, key)) throw new Error(`Unknown share-card field: ${key}`);
    return String(values[key]).replace(/[&<>"']/g, (character) => ({
      "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;",
    })[character]);
  });
  return "<!-- Generated by npm run share-card:html. Edit share-card.template.html and lib/format.mjs. -->\n" + html;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const template = readFileSync(new URL("./share-card.template.html", import.meta.url), "utf8");
  writeFileSync(new URL("./share-card.html", import.meta.url), renderShareCard(template));
}
